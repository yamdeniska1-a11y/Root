		static.ShowWindow = function(window,data)
			data = data or {}
			local align = data.Align
			local pos = data.Pos
			local size = data.Size
			local targetSide = (align == "left" and leftSide) or (align == "right" and rightSide)

			if not window.Closed then
				if not window.Aligned then
					window:SetMinimized(false)
				elseif window.Side and not data.Silent then
					static.SetSideVisible(window.Side,true)
				end
				return
			end

			window.Closed = false
			window.LastClose = tick()
			window.GuiElems.Title.TextTransparency = 0
			window.GuiElems.Minimize.Visible = false
			window.GuiElems.Close.ImageLabel.ImageTransparency = 0
			window.GuiElems.TopBar.BackgroundTransparency = 1
			window.GuiElems.Outlines.ImageTransparency = 1
			window.GuiElems.Main.Active = true
			window.GuiElems.Main.Outlines.Visible = false
			window:SetMinimized(false,3)
			window:SetResizableInternal(window.Resizable)
			window.MinimizeAnim.Enable()
			window.CloseAnim.Enable()

			if align then
				window.GuiElems.Main.GroupTransparency = 0
				if window.GuiElems.MainStroke then
					window.GuiElems.MainStroke.Transparency = 0
				end
				window:AlignTo(targetSide,pos,size,data.Silent)
			else
				if align == nil and window.ClosedSide then
					window.GuiElems.Main.GroupTransparency = 0
					if window.GuiElems.MainStroke then
						window.GuiElems.MainStroke.Transparency = 0
					end
					window:AlignTo(window.ClosedSide,window.SidePos,size,true)
					static.SetSideVisible(window.ClosedSide,true)
				else
					if table.find(visibleWindows,window) then return end

					window.SizeY = size or window.SizeY
					window.GuiElems.Main.Visible = true
					window.GuiElems.Main.Size = UDim2.new(0,window.SizeX,0,window.SizeY)
					window.GuiElems.Main.GroupTransparency = 1
					if window.GuiElems.MainStroke then
						window.GuiElems.MainStroke.Transparency = 1
					end
					local ti = TweenInfo.new(0.25, Enum.EasingStyle.Sine, Enum.EasingDirection.Out)
					window:StopTweens()
					table.insert(visibleWindows,1,window)
					updateWindows()
					window:DoTween(window.GuiElems.Main, ti, {GroupTransparency = 0})
					if window.GuiElems.MainStroke then
						window:DoTween(window.GuiElems.MainStroke, ti, {Transparency = 0})
					end
				end
			end

			window.ClosedSide = nil
			window.OnActivate:Fire()
		end

